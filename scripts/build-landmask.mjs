// Builds src/data/landmask.ts: a 1-bit map of where land is, used by the dotted globe.
// The grid is COLS x ROWS cells over longitude [-180, 180) and latitude (90, -90].
// Run with: npm run landmask   (only needed if you change the resolution)
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { createRequire } from "node:module";
import { feature } from "topojson-client";
import { geoContains } from "d3-geo";

const require = createRequire(import.meta.url);
const root = path.resolve(import.meta.dirname, "..");
const COLS = 240;
const ROWS = 120;

const topo = JSON.parse(await readFile(require.resolve("world-atlas/land-110m.json"), "utf8"));
const land = feature(topo, topo.objects.land);

const bits = new Uint8Array(Math.ceil((COLS * ROWS) / 8));
let count = 0;
for (let r = 0; r < ROWS; r++) {
  const lat = 90 - ((r + 0.5) / ROWS) * 180;
  for (let c = 0; c < COLS; c++) {
    const lon = -180 + ((c + 0.5) / COLS) * 360;
    if (geoContains(land, [lon, lat])) {
      const i = r * COLS + c;
      bits[i >> 3] |= 1 << (i & 7);
      count++;
    }
  }
}

const b64 = Buffer.from(bits).toString("base64");
const out = `// Generated by scripts/build-landmask.mjs from Natural Earth 110m land (world-atlas). Do not edit.
export const LAND_COLS = ${COLS};
export const LAND_ROWS = ${ROWS};
export const LAND_BITS = "${b64}";
`;
await writeFile(path.join(root, "src", "data", "landmask.ts"), out);
console.log(`landmask: ${count} land cells of ${COLS * ROWS}`);
